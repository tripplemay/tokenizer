//
// Token semantics in this codebase:
//   inputTokens   = total input the model saw, includes cachedInputTokens and
//                   cacheWriteTokens as subsets
//   cachedInputTokens = portion served from cache (cheap)
//   cacheWriteTokens  = portion freshly written to cache (charged separately;
//                       Anthropic charges a 1.25x premium, others bill at base
//                       input rate so cacheWrite == input)
//   outputTokens  = generated by the model
//
// "Fresh input" (charged at the base input rate) is therefore
//   max(0, inputTokens - cachedInputTokens - cacheWriteTokens)

